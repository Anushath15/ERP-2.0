-- ASK ERP 2.0: cloud copy on Supabase (PostgreSQL). Run once in Supabase > SQL Editor.
-- Design: docs/supabase-sync-design.md. The shop PC's SQLite stays the main database; this is the shared copy.
-- Collection names below follow the local table names; reconcile with the app's outbox names in Gate 2E.

create table public.shops (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  created_at timestamptz not null default now()
);

create table public.shop_members (
  shop_id uuid not null references public.shops(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner', 'manager', 'cashier')),
  active boolean not null default true,
  primary key (shop_id, user_id)
);

create table public.devices (
  shop_id uuid not null references public.shops(id) on delete cascade,
  device_id text not null,
  label text not null default '',
  revoked boolean not null default false,
  primary key (shop_id, device_id)
);

-- One generic table for every synced record (mirrors the local outbox: coll + doc_id).
create table public.sync_docs (
  shop_id uuid not null references public.shops(id) on delete cascade,
  coll text not null,
  id text not null,
  data jsonb not null,
  hlc text not null default '',
  deleted boolean not null default false,
  device_id text not null,
  seq bigint generated by default as identity,
  server_at timestamptz not null default now(),
  primary key (shop_id, coll, id)
);
create unique index sync_docs_pull on public.sync_docs (shop_id, seq);

alter table public.shops enable row level security;
alter table public.shop_members enable row level security;
alter table public.devices enable row level security;
alter table public.sync_docs enable row level security;

create function public.is_member(p_shop uuid, p_roles text[] default array['owner','manager','cashier'])
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from shop_members m
                 where m.shop_id = p_shop and m.user_id = auth.uid() and m.active and m.role = any (p_roles));
$$;

-- Read-only for members; nobody writes sync_docs directly (only push_docs below).
create policy shops_read on public.shops for select using (public.is_member(id));
create policy members_read on public.shop_members for select using (public.is_member(shop_id));
create policy devices_read on public.devices for select using (public.is_member(shop_id));
create policy docs_read on public.sync_docs for select using (public.is_member(shop_id));
revoke insert, update, delete on public.sync_docs, public.shops, public.shop_members, public.devices from anon, authenticated;

create function public.is_append_only(p_coll text) returns boolean language sql immutable as $$
  select p_coll = any (array['bills','bill_lines','bill_cancellations','payments','ledger_entries',
                             'stock_movements','reminders','audit']);
$$;

-- Atomic push of up to 100 documents. Append-only records are never changed once stored (a re-send is a no-op);
-- editable records use last-writer-wins by hlc. Cashiers may not write master data.
create function public.push_docs(p_shop uuid, p_device text, p_docs jsonb)
returns timestamptz language plpgsql security definer set search_path = public as $$
declare
  d jsonb;
  v_role text;
begin
  select role into v_role from shop_members where shop_id = p_shop and user_id = auth.uid() and active;
  if v_role is null then raise exception 'not a member of this shop' using errcode = '42501'; end if;
  if exists (select 1 from devices where shop_id = p_shop and device_id = p_device and revoked) then
    raise exception 'this computer was removed by the owner' using errcode = '42501';
  end if;
  if jsonb_typeof(p_docs) <> 'array' or jsonb_array_length(p_docs) > 100 then
    raise exception 'a batch holds at most 100 documents' using errcode = '22023';
  end if;
  insert into devices (shop_id, device_id) values (p_shop, p_device) on conflict do nothing;
  -- one push per shop at a time, so seq order equals commit order and a pull cursor never skips rows
  perform pg_advisory_xact_lock(hashtextextended(p_shop::text, 0));

  for d in select * from jsonb_array_elements(p_docs) loop
    if v_role = 'cashier' and d->>'coll' in ('products','categories','customers','dealers','settings') then
      raise exception 'cashiers cannot change %', d->>'coll' using errcode = '42501';
    end if;
    if public.is_append_only(d->>'coll') then
      insert into sync_docs (shop_id, coll, id, data, hlc, deleted, device_id)
      values (p_shop, d->>'coll', d->>'id', d->'data', coalesce(d->>'hlc',''), false, p_device)
      on conflict do nothing;
    else
      insert into sync_docs (shop_id, coll, id, data, hlc, deleted, device_id)
      values (p_shop, d->>'coll', d->>'id', d->'data', coalesce(d->>'hlc',''),
              coalesce((d->>'deleted')::boolean, false), p_device)
      on conflict (shop_id, coll, id) do update
        set data = excluded.data, hlc = excluded.hlc, deleted = excluded.deleted, device_id = excluded.device_id,
            seq = (select nextval(pg_get_serial_sequence('public.sync_docs','seq'))), server_at = now()
        where excluded.hlc > sync_docs.hlc;
    end if;
  end loop;
  return now();
end $$;

create function public.pull_docs(p_shop uuid, p_after bigint default 0, p_limit int default 300)
returns setof public.sync_docs language sql stable security invoker set search_path = public as $$
  select * from sync_docs where shop_id = p_shop and seq > p_after order by seq limit least(p_limit, 500);
$$;

-- Keeps a free project awake and lets the app check reachability with a tiny call.
create function public.ping() returns timestamptz language sql stable as $$ select now(); $$;
revoke execute on function public.push_docs, public.pull_docs, public.ping from public, anon;
grant execute on function public.push_docs, public.pull_docs, public.ping to authenticated;
grant execute on function public.ping to anon;

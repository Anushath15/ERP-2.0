// Builds lib/strings.dart from tool/strings.txt (one line per string:  key | English text).
// {name} placeholders become positional String parameters, in order of first appearance.
// Run:  dart run tool/gen_strings.dart
import 'dart:io';

void main() {
  final lines = File('tool/strings.txt').readAsLinesSync();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_strings.dart from tool/strings.txt. Do not edit by hand.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('/// Every word the app shows, in one place (English only).')
    ..writeln('class Strings {')
    ..writeln('  const Strings();')
    ..writeln();
  final seen = <String>{};
  var n = 0;
  for (final raw in lines) {
    final line = raw.trim();
    if (line.isEmpty || line.startsWith('#')) continue;
    final parts = line.split(' | ');
    if (parts.length != 2) {
      stderr.writeln('BAD LINE (need "key | English"): $line');
      exitCode = 1;
      continue;
    }
    final key = parts[0].trim();
    if (!seen.add(key)) {
      stderr.writeln('DUPLICATE KEY: $key');
      exitCode = 1;
      continue;
    }
    final text = parts[1].trim();
    final params = <String>[];
    for (final m in RegExp(r'\{(\w+)\}').allMatches(text)) {
      if (!params.contains(m.group(1))) params.add(m.group(1)!);
    }
    final esc = text.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$');
    if (params.isEmpty) {
      out.writeln("  String get $key => '$esc';");
    } else {
      final body = esc.replaceAllMapped(RegExp(r'\{(\w+)\}'), (m) => '\${${m.group(1)}}');
      out.writeln("  String $key(${params.map((p) => 'String $p').join(', ')}) => '$body';");
    }
    n++;
  }
  out.writeln('}');
  File('lib/strings.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote $n strings');
}
